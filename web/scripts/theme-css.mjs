// Writes src/theme.css from src/lib/palettes.json: one block of colour tokens
// per scheme, and a darker twin of each for the light theme (the schemes
// were chosen on the dark background; on white the light teal or the yellow
// would not read). Run it after changing palettes.json:
//   node scripts/theme-css.mjs
// lib/theme.test.ts checks that the file on disk is what this writes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'src');

const hexToHsl = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return [h * 60, s, l];
};

const hslToHex = (h, s, l) => {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
  return `#${[f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('')}`;
};

const luminance = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => lin(c / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
/** WCAG contrast of a colour against white */
const onWhite = (hex) => 1.05 / (luminance(hex) + 0.05);

/** The light theme's twin: same hue, toned down from neon, and dark enough
 *  to read on white (contrast 4:1, between the 3:1 a chart mark needs and the
 *  4.5:1 of body text). A colour that already reads stays as it is. */
export function darken(hex) {
  if (onWhite(hex) >= 4) return hex;
  const [h, s0, l0] = hexToHsl(hex);
  const s = Math.min(s0, 0.72);
  let l = l0;
  let out = hslToHex(h, s, l);
  while (onWhite(out) < 4 && l > 0.05) {
    l -= 0.01;
    out = hslToHex(h, s, l);
  }
  return out;
}

/** Every token of one scheme, the derived ones filled in. */
export function tokens(p) {
  const [s2, s3, s4, s5, s6, s7, s8] = p.series;
  return {
    dental: p.dental, gp: p.gp, alert: p.alert, 'alert-soft': p.alertSoft,
    s2, s3, s4, s5, s6, s7, s8,
    good: p.good ?? p.dental,
    bad: p.bad ?? p.alert,
    warn: p.warn ?? p.alertSoft,
    calm: p.calm ?? p.dental,
    violet: p.violet ?? s5,
    'violet-soft': p.violetSoft ?? s5,
    blue: p.blue ?? p.gp,
    mint: p.mint ?? s7,
    mid: p.mid ?? s3,
    pink: p.pink ?? s6,
    amber: p.amber ?? p.alertSoft,
    'type-adult': p.typeAdult ?? p.gp,
    'type-child': p.typeChild ?? s3,
    'type-mixed': p.typeMixed ?? p.dental,
    'type-school': p.typeSchool ?? s5,
  };
}

const decl = (t, f = (x) => x) => Object.entries(t).map(([k, v]) => `  --${k}: ${f(v)};`).join('\n');

export function themeCss() {
  const palettes = JSON.parse(readFileSync(join(SRC, 'lib', 'palettes.json'), 'utf8'));
  const out = [
    '/* Generated by scripts/theme-css.mjs from src/lib/palettes.json — do not edit by hand. */',
    '',
  ];
  for (const [key, p] of Object.entries(palettes)) {
    if (key.startsWith('_')) continue;
    const t = tokens(p);
    const dark = key === 'alap' ? `:root,\nhtml[data-palette='${key}']` : `html[data-palette='${key}']`;
    const light = key === 'alap'
      ? `:root[data-theme='light'],\nhtml[data-theme='light'][data-palette='${key}']`
      : `html[data-theme='light'][data-palette='${key}']`;
    out.push(`${dark} {\n${decl(t)}\n}`, `${light} {\n${decl(t, darken)}\n}`, '');
  }
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(SRC, 'theme.css'), themeCss());
  console.log('wrote src/theme.css');
}
